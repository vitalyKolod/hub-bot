import assert from 'node:assert/strict'
import test from 'node:test'
import { createDemo } from '../scripts/api-demo.js'

test('MongoDB + HTTP: Telegram/web shared state, RBAC, checkout, approvals, support, and notification retry', { timeout: 180000 }, async () => {
  const demo = await createDemo(0)
  const base = `http://127.0.0.1:${(demo.server.address() as any).port}`
  async function request(path: string, user = 1001, method = 'GET', body?: unknown) {
    const response = await fetch(`${base}${path}`, { method, headers: { authorization: `dev ${user}`, ...(body === undefined ? {} : { 'content-type': 'application/json' }) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
    return { status: response.status, body: await response.json() }
  }
  try {
    const { TeamModel } = await import('../src/models/Team.js')
    const { PaymentModel } = await import('../src/models/Payment.js')
    const { ApiNotificationModel } = await import('../src/models/ApiNotification.js')
    const { attemptNotification } = await import('../src/api/notifications.js')
    assert.equal((await request('/ready')).status, 200)
    assert.equal((await request('/api/me')).body.data.fio, 'Владелец демо')
    const session = await request('/api/admin/session', 9002)
    assert.equal(session.body.data.role, 'consultant')
    assert.ok(session.body.data.permissions.includes('payments.view'))
    assert.equal((await request(`/api/admin/payments/${demo.paymentId}/accept`, 9002, 'POST', {})).status, 403)
    assert.equal((await request(`/api/admin/payments/${demo.paymentId}`, 9003)).status, 403)
    assert.equal((await request(`/api/teams/${demo.teamId}`, 1003)).status, 404)
    assert.equal((await request(`/api/teams/${demo.teamId}/cart/items`, 1002, 'POST', { productId: 'cmg' })).status, 403)
    assert.equal((await request(`/api/teams/${demo.teamId}/cart/items`, 1001, 'POST', { productId: 'cmg' })).status, 200)
    const before = (await request('/api/sync')).body.data
    // This is the same shared service called by Telegram administrators.
    const { adminUpdateTeamName } = await import('../src/services/adminPanel.service.js')
    await adminUpdateTeamName(demo.teamId, 'Изменено через сервис бота', 9001)
    const after = (await request(`/api/sync?since=${before.revision}`)).body.data
    assert.equal(after.changed, true); assert.equal(after.snapshot.teams[0].name, 'Изменено через сервис бота')
    const unchanged = (await request(`/api/sync?since=${after.revision}`)).body.data
    assert.equal(unchanged.changed, false); assert.equal(unchanged.snapshot, null)
    const limitedSnapshot = await request('/api/admin/sync', 9003)
    assert.ok(limitedSnapshot.body.data.snapshot.support); assert.equal(limitedSnapshot.body.data.snapshot.payments, undefined)
    demo.setDeliveryFailure(true)
    const accepted = await request(`/api/admin/payments/${demo.paymentId}/accept`, 9001, 'POST', {})
    assert.equal(accepted.status, 200); assert.equal(accepted.body.applied, true); assert.equal(accepted.body.delivery.status, 'queued')
    assert.equal((await PaymentModel.findById(demo.paymentId))?.status, 'accepted')
    assert.equal((await TeamModel.findById(demo.teamId))?.subscriptions.get('cmg')?.status, 'active')
    demo.setDeliveryFailure(false)
    const notification = await ApiNotificationModel.findOne({ paymentId: demo.paymentId })
    assert.ok(notification)
    await ApiNotificationModel.updateOne({ _id: notification._id }, { $set: { nextAttemptAt: new Date(0) } })
    assert.equal((await attemptNotification(demo.telegram, notification.id)).status, 'sent')
    const count = demo.deliveries.filter(d => d.method === 'sendMessage').length
    const repeated = await request(`/api/admin/payments/${demo.paymentId}/accept`, 9001, 'POST', {})
    assert.equal(repeated.body.applied, false); assert.equal(demo.deliveries.filter(d => d.method === 'sendMessage').length, count)
    const created = await request('/api/support/conversations', 1001, 'POST', {})
    assert.equal(created.status, 200)
    const ticketId = created.body.data.id
    assert.equal((await request(`/api/support/conversations/${ticketId}`, 1003)).status, 404)
    assert.equal((await request(`/api/support/conversations/${ticketId}/messages`, 1001, 'POST', { text: 'Нужна помощь' })).status, 201)
    assert.equal((await request(`/api/admin/support/${ticketId}/messages`, 9003, 'POST', { text: 'Поможем' })).status, 201)
    const ticket = await request(`/api/support/conversations/${ticketId}`)
    assert.deepEqual(ticket.body.data.messages.map((m: any) => m.text), ['Нужна помощь', 'Поможем'])
    assert.equal((await request(`/api/admin/support/${ticketId}/close`, 9003, 'POST', {})).status, 200)
    assert.equal((await request(`/api/support/conversations/${ticketId}/messages`, 1001, 'POST', { text: 'Не должно отправляться' })).status, 409)
    assert.equal((await request(`/api/admin/support/${ticketId}/reopen`, 9003, 'POST', {})).status, 200)
    const cartResult = await request(`/api/teams/${demo.teamId}/cart/items`, 1001, 'POST', { productId: 'cgs' })
    const item = cartResult.body.data.items.find((i: any) => i.productId === 'cgs')
    const receipt = await request('/api/payments', 1001, 'POST', { teamId: demo.teamId, productId: 'cgs', currency: 'rub', paymentMethod: 'rub_card_mastercard', operation: 'purchase', cartItemId: item.id, receiptBase64: Buffer.from('%PDF-demo').toString('base64'), fileName: 'receipt.pdf' })
    assert.equal(receipt.status, 201); assert.equal(receipt.body.data.status, 'pending')
    assert.equal((await request(`/api/admin/payments/${receipt.body.data.id}/reject`, 9001, 'POST', { reason: 'Тестовая причина' })).body.data.status, 'rejected')
    const conv = await request(`/api/admin/payments/${demo.paymentId}/conversation`, 9001, 'POST', {})
    assert.equal(conv.status, 200)
    const convId = conv.body.data.id
    assert.equal((await request(`/api/admin/conversations/${convId}/messages`, 9001, 'POST', { text: 'Уточним оплату' })).status, 201)
    assert.equal((await request(`/api/conversations/${convId}/messages`, 1001, 'POST', { text: 'Спасибо' })).status, 201)
    assert.equal((await request(`/api/conversations/${convId}`)).body.data.messages.length, 2)
    assert.equal((await request(`/api/conversations/${convId}`, 1003)).status, 404)
    assert.equal((await request('/api/registration', 1004)).status, 200)
    assert.equal((await request('/api/teams', 1004)).status, 403)
    assert.equal((await request('/api/registration/confirm', 1004, 'POST', { confirmed: true })).status, 409)
    assert.equal((await request('/api/registration', 1004, 'PATCH', { fio: 'Новый участник', city: 'Тбилиси', church: 'Демо' })).status, 200)
    assert.equal((await request('/api/registration/confirm', 1004, 'POST', { confirmed: true })).body.applied, true)
    assert.equal((await request('/api/registration/confirm', 1004, 'POST', { confirmed: true })).body.applied, false)
    assert.equal((await request('/api/teams', 1004)).status, 200)
    const stream = await request('/api/admin/streams', 9001, 'POST', { email: 'demo@example.com', password: 'demo-only' })
    assert.equal(stream.status, 201)
    const flowNumber = stream.body.data.flowNumber
    const verification = await request(`/api/teams/${demo.teamId}/stream-verifications`, 1001, 'POST', { flowNumber })
    assert.equal(verification.status, 201)
    const verificationId = verification.body.data.id
    assert.equal((await request(`/api/admin/stream-verifications/${verificationId}/approve`, 9002, 'POST', {})).status, 403)
    assert.equal((await request(`/api/admin/stream-verifications/${verificationId}/approve`, 9001, 'POST', {})).body.applied, true)
    assert.equal((await request(`/api/admin/stream-verifications/${verificationId}/approve`, 9001, 'POST', {})).body.applied, false)
    assert.equal((await TeamModel.findById(demo.teamId))?.subscriptions.get('propresenter')?.status, 'active')
    const device = await request('/api/admin/devices', 9001, 'POST', { teamId: demo.teamId, flowNumber, name: 'Тестовый ноутбук' })
    assert.equal(device.status, 201)
    assert.equal((await request(`/api/teams/${demo.teamId}/devices/${device.body.data.id}/replace`, 1003, 'POST', { name: 'Чужой' })).status, 404)
    assert.equal((await request(`/api/teams/${demo.teamId}/devices/${device.body.data.id}/replace`, 1001, 'POST', { name: 'Новый ноутбук' })).status, 200)
    const yandexStream = await request('/api/admin/yandex360/streams', 9001, 'POST', { name: 'Демо Яндекс' })
    assert.equal(yandexStream.status, 201)
    const yandexMember = await request('/api/admin/yandex360/members', 9001, 'POST', { streamId: yandexStream.body.data.id, name: 'Тест', telegramId: 1001 })
    assert.equal(yandexMember.status, 201)
    const emailRequest = await request('/api/yandex360/email-requests', 1001, 'POST', { email: 'user@example.com' })
    assert.equal(emailRequest.status, 201)
    assert.equal((await request(`/api/admin/yandex360/requests/${emailRequest.body.data.id}/approve`, 9001, 'POST', {})).status, 200)
    const topic = await request('/api/admin/tutorials/topics', 9001, 'POST', { title: 'Демо уроки' })
    assert.equal(topic.status, 201)
    const lesson = await request(`/api/admin/tutorials/topics/${topic.body.data.id}/lessons`, 9001, 'POST', { title: 'Демо урок' })
    assert.equal(lesson.status, 201)
    const photo = { fileBase64: Buffer.from([137,80,78,71,13,10,26,10]).toString('base64'), fileName: 'demo.png', mimeType: 'image/png' }
    assert.equal((await request('/api/admin/uploads', 9003, 'POST', { ...photo, purpose: 'tutorial' })).status, 403)
    assert.equal((await request('/api/admin/uploads', 9001, 'POST', { ...photo, fileBase64: Buffer.from('invalid').toString('base64'), purpose: 'tutorial' })).status, 422)
    const media = await request('/api/admin/uploads', 9001, 'POST', { ...photo, purpose: 'tutorial' })
    assert.equal(media.status, 201); assert.equal(media.body.data.telegramFileId, undefined)
    assert.equal((await request(`/api/admin/tutorials/lessons/${lesson.body.data.id}/media`, 9001, 'POST', { uploadId: media.body.data.id })).status, 200)
    assert.equal((await request(`/api/admin/tutorials/lessons/${lesson.body.data.id}`, 9001, 'PATCH', { published: true })).status, 200)
    assert.equal((await request(`/api/tutorials/lessons/${lesson.body.data.id}`)).status, 200)
    assert.equal((await request(`/api/support/conversations/${ticketId}/attachments`, 1001, 'POST', { fileBase64: Buffer.from('%PDF-demo').toString('base64'), fileName: 'demo.pdf', mimeType: 'application/pdf', text: 'Вложение' })).status, 201)
    const broadcast = await request('/api/admin/broadcasts', 9001, 'POST', { audience: 'all', text: 'Тестовая рассылка' })
    assert.equal(broadcast.status, 201); assert.equal(broadcast.body.data.status, 'draft')
    const broadcastId = broadcast.body.data.id
    assert.equal((await request(`/api/admin/broadcasts/${broadcastId}/send`, 9001, 'POST', { confirmed: false })).status, 422)
    assert.equal((await request(`/api/admin/broadcasts/${broadcastId}/send`, 9001, 'POST', { confirmed: true })).body.applied, true)
    assert.equal((await request(`/api/admin/broadcasts/${broadcastId}/send`, 9001, 'POST', { confirmed: true })).body.applied, false)
    const { processBroadcastBatch } = await import('../src/services/broadcast.service.js')
    await processBroadcastBatch(demo.telegram); await processBroadcastBatch(demo.telegram)
    const completed = await request(`/api/admin/broadcasts/${broadcastId}`, 9001)
    assert.equal(completed.body.data.status, 'completed'); assert.equal(completed.body.data.success, completed.body.data.total)
    console.log('Isolated MongoDB integration checks passed; no real Telegram or production access.')
  } finally { await demo.close() }
})
